/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_TIM2_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */

  DriveBase_Init(&drive, &htim2, &htim3, &htim4);

  if (DriveBase_Start(&drive) != HAL_OK)
  {
	  Error_Handler();
  }

  Serial_Comm_Init(&huart1);

  CommandWatchdog_Init(&command_wd, WATCHDOG_TIMEOUT_MS);

  last_tick = HAL_GetTick();
  last_encoder_tx_tick = HAL_GetTick();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

    /* Xu ly du lieu UART nhan duoc */
    Serial_Comm_Process();

    uint32_t now = HAL_GetTick();

    if (CommandWatchdog_Update(&command_wd, now))
    {
        CommandWatchdog_Disarm(&command_wd);
        DriveBase_SafeStop(&drive);
    }

    /* Lay lenh CMD moi nhat neu co */
    if (Serial_Comm_GetCommand(&received_cmd))
    {
        if (received_cmd.type == SERIAL_CMD_DISARM) 
        {
            CommandWatchdog_Disarm(&command_wd);
            DriveBase_SafeStop(&drive);
        }
        else if (received_cmd.type == SERIAL_CMD_ARM && drive_fault == DRIVE_OK)
        {
            DriveBase_SafeStop(&drive);
            drive_enable = 1;
            CommandWatchdog_Arm(&command_wd, now);
        }
        else if (received_cmd.type == SERIAL_CMD_VELOCITY &&
                 drive_enable && command_wd.armed &&
                 now - received_cmd.received_ms < command_wd.timeout_ms)
        {
            cmd_v = received_cmd.linear_x;
            cmd_w = received_cmd.angular_z;
            CommandWatchdog_Refresh(&command_wd, now);
        }
    }

    /* Dieu khien dong co */
    elapsed = now - last_tick;

    if (elapsed >= CTRL_PERIOD_MS)
    {
        last_tick = now;
        DriveBase_Update(&drive, elapsed);
    }

    /* Gui Encoder moi 100 ms */
    if (now - last_encoder_tx_tick >= 100)
    {
        last_encoder_tx_tick = now;

        /* Lay tong xung da duoc chuan hoa */
        int32_t left_count = drive.left.enc.total;
        int32_t right_count = drive.right.enc.total;

        /* Truyen Encoder qua USART1 */
        Serial_Comm_SendEncoder(left_count, right_count);
    }


    if (drive_fault != DRIVE_OK && command_wd.armed)
    {
        CommandWatchdog_Disarm(&command_wd);
        DriveBase_SafeStop(&drive);
    }


  }
  /* USER CODE END 3 */
}

